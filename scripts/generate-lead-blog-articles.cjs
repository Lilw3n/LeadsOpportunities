const fs = require("fs");
const path = require("path");

const planPath = path.join(__dirname, "..", "data", "blog-lead-content-plan.json");
const outPath = path.join(__dirname, "blog-lead-articles.generated.cjs");

const MONTHS = [
  "Janvier",
  "Fevrier",
  "Mars",
  "Avril",
  "Mai",
  "Juin",
  "Juillet",
  "Aout",
  "Septembre",
  "Octobre",
  "Novembre",
  "Decembre",
];

const SECTION_DEFAULTS = {
  animaux: { tagClass: "tag-animaux", need: "animaux" },
  auto: { tagClass: "tag-auto", need: "auto" },
  finance: { tagClass: "tag-immo", need: "credit-immo" },
  habitat: { tagClass: "tag-habitation", need: "habitation" },
  patrimoine: { tagClass: "tag-patrimoine", need: "assurance-vie" },
  prevoyance: { tagClass: "tag-prevoyance", need: "prevoyance" },
  pro: { tagClass: "tag-pro", need: "rc-pro" },
  sante: { tagClass: "tag-sante", need: "sante" },
  vtc: { tagClass: "tag-vtc", need: "vtc" },
};

function parseArgs(argv) {
  return argv.reduce(
    function (args, arg) {
      if (arg === "--all") args.all = true;
      else if (arg === "--dry-run") args.dryRun = true;
      else if (arg.indexOf("--date=") === 0) args.date = arg.slice("--date=".length);
      else if (arg.indexOf("--count=") === 0) args.count = Number(arg.slice("--count=".length));
      return args;
    },
    { all: false, count: 1, date: new Date().toISOString().slice(0, 10), dryRun: false }
  );
}

function assertDate(value, label) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value || "")) {
    throw new Error(label + " must use YYYY-MM-DD format");
  }
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function readExistingArticles() {
  if (!fs.existsSync(outPath)) return [];
  delete require.cache[require.resolve(outPath)];
  var mod = require(outPath);
  return Array.isArray(mod.articles) ? mod.articles : [];
}

function uniqueByFile(articles) {
  var seen = {};
  return articles.filter(function (article) {
    if (!article || !article.file || seen[article.file]) return false;
    seen[article.file] = true;
    return true;
  });
}

function validateItem(item) {
  [
    "publishAt",
    "file",
    "section",
    "tag",
    "title",
    "description",
    "cardExcerpt",
    "intro",
    "urgency",
    "conversion",
  ].forEach(function (field) {
    if (!item[field]) throw new Error("Missing " + field + " for lead article");
  });
  assertDate(item.publishAt, "publishAt for " + item.file);
  if (!/\.html$/.test(item.file)) throw new Error("Article file must end with .html: " + item.file);
  if (!SECTION_DEFAULTS[item.section]) throw new Error("Unknown blog section: " + item.section);
  ["painPoints", "decisionCriteria", "documents", "keywords", "related"].forEach(function (field) {
    if (!Array.isArray(item[field]) || !item[field].length) {
      throw new Error("Missing non-empty " + field + " for " + item.file);
    }
  });
}

function metaFromDate(date) {
  var parts = date.split("-");
  var month = MONTHS[Number(parts[1]) - 1] || "";
  return "8 min - " + month + " " + parts[0];
}

function articleFromItem(item) {
  validateItem(item);
  var defaults = SECTION_DEFAULTS[item.section];
  var cta =
    item.cta ||
    {
      href: "../landings/questionnaire.html?need=" + defaults.need + "&journey=standard",
      label: "Questionnaire " + item.tag,
    };

  return {
    file: item.file,
    section: item.section,
    tag: item.tag,
    tagClass: item.tagClass || defaults.tagClass,
    title: item.title,
    description: item.description,
    meta: item.meta || metaFromDate(item.publishAt),
    cardExcerpt: item.cardExcerpt,
    cta: cta,
    keywords: item.keywords,
    publishAt: item.publishAt,
    blocks: [
      { type: "p", text: item.intro },
      { type: "h2", text: "1. Pourquoi agir maintenant" },
      { type: "p", text: item.urgency },
      { type: "h2", text: "2. Les signaux a verifier avant de signer" },
      { type: "ul", items: item.painPoints },
      { type: "h2", text: "3. Comparer les offres a garanties equivalentes" },
      { type: "ul", items: item.decisionCriteria },
      { type: "bridge" },
      { type: "h2", text: "4. Documents utiles pour un devis rapide" },
      { type: "ul", items: item.documents },
      { type: "h2", text: "5. Obtenir un devis exploitable" },
      { type: "p", text: item.conversion },
      {
        type: "p",
        text:
          "La bonne sequence : lire les garanties, repondre au questionnaire, puis comparer les offres avec un conseiller. Vous evitez ainsi le devis trop vague qui ne debouche pas sur une vraie solution.",
      },
    ],
    related: item.related,
  };
}

function writeGenerated(articles, date) {
  var output =
    "// Generated by scripts/generate-lead-blog-articles.cjs. Do not edit manually.\n" +
    "module.exports = " +
    JSON.stringify({ generatedAt: date, articles: articles }, null, 2) +
    ";\n";
  fs.writeFileSync(outPath, output);
}

function main() {
  var args = parseArgs(process.argv.slice(2));
  assertDate(args.date, "--date");
  if (!args.all && (!Number.isInteger(args.count) || args.count < 1)) {
    throw new Error("--count must be a positive integer");
  }

  var plan = readJson(planPath);
  var planned = (plan.articles || []).slice().sort(function (a, b) {
    return a.publishAt.localeCompare(b.publishAt);
  });
  var existing = readExistingArticles();
  var published = existing.reduce(function (acc, article) {
    acc[article.file] = true;
    return acc;
  }, {});
  var due = planned.filter(function (item) {
    validateItem(item);
    return item.publishAt <= args.date && !published[item.file];
  });
  var selected = args.all ? due : due.slice(0, args.count);
  var nextArticles = uniqueByFile(existing.concat(selected.map(articleFromItem)));

  if (args.dryRun) {
    console.log("Date:", args.date);
    console.log("Already published:", existing.length);
    console.log("Due:", due.map(function (item) { return item.file; }).join(", ") || "none");
    console.log("Selected:", selected.map(function (item) { return item.file; }).join(", ") || "none");
    return;
  }

  writeGenerated(nextArticles, args.date);
  console.log("Lead articles published:", selected.length);
  selected.forEach(function (item) {
    console.log("written:", item.file, "(" + item.publishAt + ")");
  });
  if (!selected.length) console.log("No lead article due for", args.date);
}

main();
